"""2b-4b M4 recovery, task 15: `retained_out`, only on qualified historical evidence (design revision 6 §4, revision 7
§4; ruling 5 on the clock skew).

- `execution_evidence.closed_at` and `closed_seen_at`: Temporal's close time of that exact run, from the evidence
  cadence's describe of it or its history's close event, and when it was seen. Step 60 copies both into the known row
  it writes `run_not_found` (0060's columns), before step 80 sweeps the evidence.
- `target_namespace_registrations` and `target_qualification_intervals`: the persistent-target qualification's record
  (a later, separate approval), platform tables no application role writes; `dewpoint_retention` reads them. A
  namespace's registration, and each interval over which the target enforced a retention maximum with archival off,
  with its retention-timer jitter maximum and its largest clock difference between Temporal and the database
  (`clock_skew_max`: no default, ruling 5). Any value missing is NULL, and a NULL never qualifies anything. Empty until
  that qualification fills them, so nothing qualifies before then.

One transaction, Alembic's own, each lock wait bounded (5 s): two nullable columns (no rewrite) and two new tables.
Its downgrade refuses while a captured close, a registration or an interval is kept, its locks taken before it
checks."""

from alembic import op

revision = "0063"
down_revision = "0062"
branch_labels = None
depends_on = None

LOCK_TIMEOUT = "SET LOCAL lock_timeout = '5s'"
UPGRADE = [
    "ALTER TABLE execution_evidence ADD COLUMN closed_at timestamptz NULL, ADD COLUMN closed_seen_at timestamptz NULL",
    """CREATE TABLE target_namespace_registrations (
  namespace text PRIMARY KEY,
  registered_at timestamptz NOT NULL,
  evidence text NOT NULL)""",
    """CREATE TABLE target_qualification_intervals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  namespace text NOT NULL,
  valid_from timestamptz NOT NULL,
  valid_to timestamptz NOT NULL,
  retention_max interval NULL,
  archival_off boolean NULL,
  jitter_max interval NULL,
  clock_skew_max interval NULL,
  evidence text NOT NULL,
  CONSTRAINT target_qualification_intervals_span CHECK (valid_from < valid_to))""",
    "CREATE INDEX target_qualification_intervals_namespace ON target_qualification_intervals (namespace, valid_from)",
    "REVOKE ALL ON target_namespace_registrations, target_qualification_intervals FROM PUBLIC",
    "GRANT SELECT ON target_namespace_registrations, target_qualification_intervals TO dewpoint_retention",
]
LOCKED = ("LOCK TABLE execution_evidence, target_namespace_registrations, target_qualification_intervals "
          "IN ACCESS EXCLUSIVE MODE")  # fmt: skip
REFUSE_DOWNGRADE = """DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM execution_evidence WHERE closed_at IS NOT NULL OR closed_seen_at IS NOT NULL)
     OR EXISTS (SELECT 1 FROM target_namespace_registrations)
     OR EXISTS (SELECT 1 FROM target_qualification_intervals) THEN
    RAISE EXCEPTION '0063 refused: a captured close, a registration or a qualification interval is kept';
  END IF;
END $$"""


def upgrade() -> None:
    for statement in (LOCK_TIMEOUT, *UPGRADE):
        op.execute(statement)


def downgrade() -> None:
    for statement in (LOCK_TIMEOUT, LOCKED, REFUSE_DOWNGRADE):
        op.execute(statement)
    op.execute("DROP TABLE target_qualification_intervals")
    op.execute("DROP TABLE target_namespace_registrations")
    op.execute("ALTER TABLE execution_evidence DROP COLUMN closed_seen_at, DROP COLUMN closed_at")
